-- 보낼 메일을 적어 두는 표(outbox). 가입 트랜잭션이 사용자 행과 같이 넣고, 집배원(스케줄러)이 꺼내 보낸다
-- 이메일 주소와 인증 토큰은 적지 않는다. 사용자 id만 두고 보낼 때 찾는다
-- users를 외래 키로 묶지 않는다. 보낼 메시지의 기록이라 사용자 행과 따로 산다
create table outbox_message (
    id bigint generated by default as identity,
    type varchar(255) not null
        check ((type in ('VERIFICATION_MAIL','ALREADY_REGISTERED_MAIL'))),
    user_id bigint not null,
    status varchar(255) not null
        check ((status in ('PENDING','SENT','FAILED'))),
    attempts integer not null,
    -- 이 시각부터 다시 집어도 된다. 재시도 간격과 찜(집은 뒤 5분)을 이 칸 하나로 한다
    next_attempt_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    sent_at timestamp(6) with time zone,
    primary key (id)
);

-- 집배원은 "대기이고 next_attempt_at <= 지금"만 찾는다. 보낸 줄이 쌓여도 대기 줄만 훑게 한다
create index idx_outbox_message_pending on outbox_message (next_attempt_at) where status = 'PENDING';
