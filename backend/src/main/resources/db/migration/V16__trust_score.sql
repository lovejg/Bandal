-- 신뢰도 점수 변동 기록. 방 상태 변경(Kafka 글) 하나가 사람마다 몇 점을 움직였는지 한 줄씩 남긴다
-- 같은 글을 두 번 읽어도 한 번만 반영되게 (event_id, user_id)가 유니크다(알림 표와 같은 방식)
-- 화면이 "왜 깎였나"를 보여 줄 때도 이 표를 읽는다
create table trust_score_change (
    id bigint generated by default as identity,
    event_id bigint not null,
    user_id bigint not null,
    group_order_id bigint not null,
    store_name varchar(255) not null,
    reason varchar(40) not null
        check (reason in ('DELIVERED', 'HOST_CANCELED_AFTER_CLOSE', 'HOST_CANCELED_WHILE_SETTLING',
                          'HOST_DID_NOT_ORDER', 'DID_NOT_PAY')),
    delta int not null,
    occurred_at timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_trust_score_change_event_user unique (event_id, user_id)
);
create index idx_trust_score_change_user on trust_score_change (user_id, id desc);

-- 점수는 0~100
alter table users
    add constraint ck_users_trust_score_range check (trust_score between 0 and 100);

-- 점수가 낮은 채로 탈퇴하면, 같은 메일로 다시 가입해 점수를 되돌리지 못하게 메일의 해시만 남긴다(점수가 50 미만일 때만)
-- 메일 자체는 지운다. 해시는 비밀 키를 섞은 HMAC이라 학교 메일 형식으로 하나씩 대 봐도 되돌릴 수 없다
alter table users
    add column withdrawn_email_hash varchar(64);
create index idx_users_withdrawn_email_hash on users (withdrawn_email_hash) where withdrawn_email_hash is not null;
