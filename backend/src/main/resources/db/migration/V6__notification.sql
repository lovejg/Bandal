-- 앱 안 알림함. 알림 컨슈머(worker)가 Kafka 글을 읽고 받는 사람마다 한 줄씩 넣는다
-- 문장은 저장하지 않는다. 사실(상태, 가게 이름, 금액, 사유)만 두고 화면이 문장을 만든다
-- users, group_order를 외래 키로 묶지 않는다. 그 순간의 사실을 옮겨 적은 기록이라 원래 행과 따로 산다
create table notification (
    id bigint generated by default as identity,
    -- 상태 변경 번호(outbox 줄 id, Kafka 헤더 eventId). 같은 글을 두 번 읽어도 한 줄만 남게 받는 사람과 묶어 유니크
    event_id bigint not null,
    -- 받는 사람
    user_id bigint not null,
    group_order_id bigint not null,
    store_name varchar(255) not null,
    -- 바뀐 뒤 상태
    status varchar(255) not null
        check ((status in ('RECRUITING','CLOSED','SETTLING','ORDERED','DELIVERED','CANCELED'))),
    -- 취소일 때만
    cancel_reason varchar(255),
    -- 정산 시작일 때 이 사람이 보낼 돈. 정산표가 없으면 null
    amount bigint,
    -- 상태가 바뀐 시각(알림이 가리키는 일이 일어난 때)
    occurred_at timestamp(6) with time zone not null,
    -- null이면 안 읽음
    read_at timestamp(6) with time zone,
    primary key (id),
    constraint uk_notification_event_user unique (event_id, user_id)
);

-- 알림함은 "내 알림을 최신순으로"만 찾는다
create index idx_notification_user on notification (user_id, id desc);
