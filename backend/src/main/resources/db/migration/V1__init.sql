-- 처음 테이블. Flyway로 옮길 때 엔티티에서 Hibernate가 만들던 것을 그대로 옮겼다(타입, 길이, check, unique 모두 같다).
-- 바꾼 건 제약 이름과 열 순서뿐이다. 이 파일은 한 번 돌고 나면 고치지 않는다. 바꿀 일이 생기면 V2를 새로 쓴다.

create table university (
    id bigint generated by default as identity,
    name varchar(255),
    email_domain varchar(255) not null,
    primary key (id),
    constraint uk_university_email_domain unique (email_domain)
);

create table users (
    id bigint generated by default as identity,
    university_id bigint not null,
    email varchar(255) not null,
    password varchar(255) not null,
    nickname varchar(255) not null,
    email_verified_at timestamp(6) with time zone,
    trust_score integer not null,
    bank_name varchar(255),
    account_number varchar(255),
    account_holder varchar(255),
    primary key (id),
    constraint uk_users_email unique (email),
    constraint uk_users_nickname unique (nickname),
    constraint fk_users_university foreign key (university_id) references university (id)
);

create table pickup_spot (
    id bigint generated by default as identity,
    university_id bigint not null,
    name varchar(30) not null,
    normalized_name varchar(30) not null,
    description varchar(100),
    primary key (id),
    -- 같은 학교에 같은 이름 거점은 하나. 동시에 만들면 이 제약이 막는다
    constraint uk_pickup_spot_university_name unique (university_id, normalized_name),
    constraint fk_pickup_spot_university foreign key (university_id) references university (id)
);

create table group_order (
    id bigint generated by default as identity,
    host_id bigint not null,
    pickup_spot_id bigint not null,
    store_name varchar(255) not null,
    min_order_amount bigint not null,
    deadline_at timestamp(6) with time zone not null,
    capacity integer not null,
    participant_count integer not null,
    status varchar(255) not null
        check ((status in ('RECRUITING','CLOSED','SETTLING','ORDERED','DELIVERED','CANCELED'))),
    closed_at timestamp(6) with time zone,
    delivery_fee bigint,
    settlement_started_at timestamp(6) with time zone,
    total_paid_amount bigint,
    ordered_at timestamp(6) with time zone,
    delivered_at timestamp(6) with time zone,
    canceled_at timestamp(6) with time zone,
    cancel_type varchar(255)
        check ((cancel_type in ('HOST_WHILE_RECRUITING','HOST_WHILE_CLOSED','HOST_WHILE_SETTLING','DEADLINE_UNMET','CLOSED_TIMEOUT','SETTLING_TIMEOUT'))),
    cancel_reason varchar(255),
    primary key (id),
    constraint fk_group_order_host foreign key (host_id) references users (id),
    constraint fk_group_order_pickup_spot foreign key (pickup_spot_id) references pickup_spot (id)
);

create table participation (
    id bigint generated by default as identity,
    group_order_id bigint not null,
    user_id bigint not null,
    joined_at timestamp(6) with time zone not null,
    primary key (id),
    -- 한 사람은 한 방에 한 번만
    constraint uk_participation_group_order_user unique (group_order_id, user_id),
    constraint fk_participation_group_order foreign key (group_order_id) references group_order (id),
    constraint fk_participation_user foreign key (user_id) references users (id)
);

create table order_item (
    id bigint generated by default as identity,
    participation_id bigint not null,
    menu_name varchar(50) not null,
    options varchar(100),
    unit_price bigint not null,
    quantity integer not null,
    edited_by_host boolean not null,
    primary key (id),
    constraint fk_order_item_participation foreign key (participation_id) references participation (id)
);

create table settlement (
    id bigint generated by default as identity,
    group_order_id bigint not null,
    user_id bigint not null,
    host boolean not null,
    menu_total_amount bigint not null,
    fee_share bigint not null,
    total_amount bigint not null,
    marked_paid_at timestamp(6) with time zone,
    confirmed_paid_at timestamp(6) with time zone,
    confirm_revoked_at timestamp(6) with time zone,
    refund_sent_at timestamp(6) with time zone,
    refund_received_at timestamp(6) with time zone,
    payment_denied_at timestamp(6) with time zone,
    primary key (id),
    constraint fk_settlement_group_order foreign key (group_order_id) references group_order (id),
    constraint fk_settlement_user foreign key (user_id) references users (id)
);
